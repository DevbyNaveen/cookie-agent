#!/usr/bin/env python3
"""Generates Sources/Enkeon/PhosphorIcons.swift: the Phosphor icons the app uses, as SVG path data.

  scripts/phosphor.py PATH/TO/@phosphor-icons/react

The same icons as the Enkeon web Console (@phosphor-icons/react 2.x, MIT, Copyright (c) 2020 Phosphor
Icons). Each icon's "regular" and "fill" paths are read from the package's dist/defs/<Name>.es.js.
"""
import os, re, sys

ICONS = ["House", "Brain", "BookOpenText", "Scissors", "TextAa", "GitDiff", "Plugs", "GearSix",
         "ArrowSquareOut", "SidebarSimple", "Microphone", "Sparkle", "Waveform",
         "CheckCircle", "Clock", "WarningCircle", "Copy", "Trash", "Check", "X", "ArrowUUpLeft", "Keyboard", "CursorClick",
         "MagnifyingGlass", "Plus", "PencilSimple", "ArrowsDownUp", "NotePencil", "Lightning", "ChatCircleText",
         "EnvelopeSimple", "Code", "Briefcase"]
WEIGHTS = ["regular", "fill"]


def paths(source, weight):
    start = source.index(f'"{weight}"')
    block = source[start:source.index("]", start)]
    return re.findall(r'd: "([^"]+)"', block)


def main():
    package = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
    defs = os.path.join(package, "dist", "defs")
    lines = [
        "// Generated by scripts/phosphor.py from @phosphor-icons/react (MIT, Copyright (c) 2020 Phosphor Icons).",
        "// The same icon set as the Enkeon web Console. Do not edit by hand: regenerate.",
        "",
        "enum PhosphorPaths {",
        "    /// Path data on Phosphor's 256 × 256 grid, by icon name, then weight.",
        "    static let all: [String: [String: [String]]] = [",
    ]
    for name in ICONS:
        source = open(os.path.join(defs, f"{name}.es.js")).read()
        lines.append(f'        "{name}": [')
        for weight in WEIGHTS:
            found = paths(source, weight)
            if not found:
                sys.exit(f"{name}: no {weight} path")
            joined = ", ".join('"' + d + '"' for d in found)
            lines.append(f'            "{weight}": [{joined}],')
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "Enkeon", "PhosphorIcons.swift")
    open(out, "w").write("\n".join(lines))
    print(f"wrote {len(ICONS)} icons × {len(WEIGHTS)} weights to {os.path.relpath(out)}")


if __name__ == "__main__":
    main()
